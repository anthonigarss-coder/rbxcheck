"""Lecture des dimensions d'une image (PNG / JPEG) sans dépendance externe."""

from __future__ import annotations

import struct


def image_info(data: bytes) -> tuple[str, int, int] | None:
    """Renvoie (format, largeur, hauteur) ou None si format inconnu."""
    if data[:8] == b"\x89PNG\r\n\x1a\n" and len(data) >= 24:
        w, h = struct.unpack(">II", data[16:24])
        return "png", w, h
    if data[:2] == b"\xff\xd8":
        return _jpeg(data)
    return None


def _jpeg(data: bytes) -> tuple[str, int, int] | None:
    i = 2
    n = len(data)
    while i + 9 < n:
        if data[i] != 0xFF:
            i += 1
            continue
        marker = data[i + 1]
        if marker == 0xFF:
            i += 1
            continue
        if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
            i += 2
            continue
        seg_len = struct.unpack(">H", data[i + 2 : i + 4])[0]
        # SOF0..SOF15 sauf DHT(C4), JPG(C8), DAC(CC)
        if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
            h, w = struct.unpack(">HH", data[i + 5 : i + 9])
            return "jpeg", w, h
        i += 2 + seg_len
    return None
